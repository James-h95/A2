"""Write results/RESULTS.md: a readable summary generated only from results/runs.csv.

  python scripts/results_summary.py

Main model, ablations and baselines B2-B5 come from the Kaggle GPU runs
(notes contain 'kaggle-gpu-run1' or 'kaggle-gpu-run2'). The Stage 3/4 sweep, B1 and the
oracle come from the earlier local runs. Validation only: the test set is still locked.
"""
import json
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from src.runlog import read_runs  # noqa: E402

M = ("bleu1", "meteor", "rougeL", "em", "f1")
runs = [r for r in read_runs() if r["split"] == "val"]
gpu = [r for r in runs if "kaggle-gpu-run" in r["notes"]]
local = [r for r in runs if "kaggle-gpu-run" not in r["notes"]]


def agg(rs):
    vals = {m: [float(r[m]) for r in rs] for m in M}
    return {m: (statistics.mean(v), statistics.stdev(v) if len(v) > 1 else None) for m, v in vals.items()}


def cell(x):
    mu, sd = x
    return f"{mu:.2f}" + (f" ± {sd:.2f}" if sd is not None else "")


def table(rows):
    out = ["| Model | What it is | n | BLEU-1 | METEOR | **ROUGE-L** | EM | F1 |", "|---|---|---|---|---|---|---|---|"]
    for name, desc, rs in rows:
        if not rs:
            continue
        a = agg(rs)
        out.append(f"| {name} | {desc} | {len(rs)} | " + " | ".join(
            (f"**{cell(a[m])}**" if m == "rougeL" else cell(a[m])) for m in M) + " |")
    return "\n".join(out)


def table_delta(rows, ref_rs):
    ref = statistics.mean(float(r["rougeL"]) for r in ref_rs)
    out = ["| Model | What it is | n | **ROUGE-L** | Δ vs reference | EM | F1 | BLEU-1 | METEOR |",
           "|---|---|---|---|---|---|---|---|---|"]
    for name, desc, rs in rows:
        a = agg(rs)
        d = "(reference)" if rs is ref_rs else f"{a['rougeL'][0] - ref:+.2f}"
        out.append(f"| {name} | {desc} | {len(rs)} | **{cell(a['rougeL'])}** | {d} | {cell(a['em'])} | {cell(a['f1'])} | "
                   f"{cell(a['bleu1'])} | {cell(a['meteor'])} |")
    return "\n".join(out)


def pick(src, model):
    return [r for r in src if r["model"] == model]


main = pick(gpu, "A5_single_span")      # main model v2 (single silver span); identical config to run 1's A5
v1 = pick(gpu, "cand_lr5e-4_ft")         # main model v1 (wide soft targets)
L = ["# Results so far (validation set)", "",
     "Generated by `scripts/results_summary.py` from `results/runs.csv`. **Do not edit by hand.** Re-run the script instead.",
     "All scores are on the 1,076-question validation split. **The test set has not been used yet.**",
     "± = standard deviation over 3 random seeds. ROUGE-L is the headline metric (used for model selection).",
     "**Main model = v2**: TweetBiDAF trained on a single silver span (`results/FROZEN_CONFIG.json`). v1 used wide soft targets.", "",
     "## Main comparison", "",
     table([
         ("**TweetBiDAF v2 (ours)**", "main model, trained from scratch, single silver span", main),
         ("TweetBiDAF v1 (ours)", "same model trained on wide soft targets", v1),
         ("B1", "lexical word-matching rules (no learning)", pick(local, "B1_lexical")),
         ("B2", "our model with every task-specific part off", pick(gpu, "B2_vanilla")),
         ("B3", "BERTweet, pretrained, fine-tuned by us", pick(gpu, "B3_bertweet-base")),
         ("B4", "t5-small, pretrained, fine-tuned by us", pick(gpu, "B4_t5-small")),
         ("B5", "Qwen2.5-1.5B-Instruct, 4-shot prompt, no training", pick(gpu, "B5_Qwen2.5-1.5B-Instruct_4shot")),
         ("Oracle", "best possible answer copied from the tweet (ceiling for B1–B3 and ours)",
          [r for r in pick(local, "oracle") if json.loads(r["config"]).get("max_span_len") == 15
           and json.loads(r["config"]).get("use_normaliser") is True]),
     ]), "",
     "## Ablations on the main model (v2): remove one part, retrain, compare", "",
     table_delta([
         ("**Main model v2**", "everything on, single silver span", main),
         ("A1", "− character-level CNN", pick(gpu, "S_A1_no_char")),
         ("A2", "− tweet normaliser and token flags", pick(gpu, "S_A2_no_norm_flags")),
         ("A3", "− gated self-attention", pick(gpu, "S_A3_no_selfattn")),
         ("A4", "− question-to-context attention (C2Q only)", pick(gpu, "S_A4_c2q_only")),
         ("A5", "wide soft targets instead of a single span (= v1)", v1),
         ("B2", "all of the above removed", pick(gpu, "B2_vanilla")),
     ], main), "",
     "## Soft-target width experiment (same 8,057 training examples; only the training target changes)", "",
     table_delta([
         ("Single span", "1 target span per question (main v2)", main),
         ("Narrow soft", "soft_tau 0.85, ~1.3 spans per question", pick(gpu, "soft_tau0.85")),
         ("Medium soft", "soft_tau 0.7, ~3.6 spans per question", pick(gpu, "soft_tau0.7")),
         ("Wide soft", "soft_tau 0.5, ~17 spans per question (v1)", v1),
     ], main), "",
     "## Earlier ablations on v1 (soft-target base), kept for reference", "",
     table_delta([
         ("Main model v1", "wide soft targets", v1),
         ("A1", "− character-level CNN", pick(gpu, "A1_no_char")),
         ("A2", "− tweet normaliser and token flags", pick(gpu, "A2_no_norm_flags")),
         ("A3", "− gated self-attention", pick(gpu, "A3_no_selfattn")),
         ("A4", "− question-to-context attention (C2Q only)", pick(gpu, "A4_c2q_only")),
         ("A5", "single silver span (became main v2)", main),
     ], v1), "",
     "## Hyperparameter selection (Stage 4, local Mac runs)", "",
     table([
         ("Base", "lr 1e-3, random word init (3 seeds)", pick(local, "main_v1") + pick(local, "sw_base")),
         ("lr 5e-4", "", pick(local, "sw_lr5e-4")),
         ("FastText init", "seed 1 only", pick(local, "sw_fasttext")),
         ("**Frozen**", "lr 5e-4 + FastText (in-domain, trained on train split)", pick(local, "cand_lr5e-4_ft")),
     ]), "",
     "## Where everything is", "",
     "- `results/runs.csv`: every run ever logged (one row per run: model, config, seed, all metrics, notes incl. device).",
     "- `results/PROGRESS.md`: stage-by-stage log of what was built, the key numbers and surprises.",
     "- `results/DATA_REPORT.md`: dataset statistics.",
     "- `results/logs/`: raw training logs. `results/history/`: per-epoch loss and val scores (JSON).",
     "- `results/preds/`: every model's validation predictions (for error analysis).",
     "- `results/FROZEN_CONFIG.json`: the final main-model configuration.",
     ]
(ROOT / "results" / "RESULTS.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print("\n".join(L))
