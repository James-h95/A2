"""Stage 0 data report for TweetQA. Standard library only.

Distribution statistics are computed on train only. For test we check
only size, format and that gold answers are present, so test never
influences design decisions.
"""
import ast
import collections
import csv
import random
import re
import string
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"
OUT = ROOT / "results" / "DATA_REPORT.md"

ANSWER_ITEM = re.compile(r"'(?:[^'\\]|\\.)*'|\"(?:[^\"\\]|\\.)*\"", re.S)
TOKEN = re.compile(
    r"https?://\S+|www\.\S+"          # url
    r"|[@#]\w+"                       # mention / hashtag
    r"|\d+(?:[.,:/]\d+)*(?:am|pm)?"   # number, time, date-ish
    r"|\w+(?:['’]\w+)*"               # word with internal apostrophes
    r"|[^\w\s]",                      # any other single symbol (incl. emoji)
    re.I,
)
EMOJI = re.compile("[\U0001F000-\U0001FAFF☀-➿️]")
URL = re.compile(r"https?://\S+|www\.\S+")
MONTHS = ("january february march april may june july august september "
          "october november december jan feb mar apr jun jul aug sep sept oct nov dec").split()
BYLINE = re.compile(r"\(@\w+\)\s+\w+\s+\d{1,2},\s+\d{4}\s*$")


def parse_answers(s):
    items = [ast.literal_eval(m) for m in ANSWER_ITEM.findall(s)]
    if not items:
        raise ValueError(f"unparseable answer field: {s!r}")
    return items


def load(split):
    with open(DATA / f"{split}.csv", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    for r in rows:
        r["answers"] = parse_answers(r["Answer"])
    return rows


def tok(s):
    return TOKEN.findall(s)


def normalise(s):
    s = s.lower()
    # strip ASCII and Unicode punctuation (em-dash, curly quotes, ...) -> space
    s = "".join(" " if (ch in string.punctuation or unicodedata.category(ch).startswith("P")) else ch for ch in s)
    s = re.sub(r"\b(a|an|the)\b", " ", s)
    return " ".join(s.split())


def pct(xs, ps=(50, 75, 90, 95, 99, 100)):
    xs = sorted(xs)
    return {p: xs[min(len(xs) - 1, int(round(p / 100 * (len(xs) - 1))))] for p in ps}


def answer_kind(a, tweet):
    a_s = a.strip()
    kinds = set()
    if re.fullmatch(r"@?\w+", a_s) and ("@" + a_s.lstrip("@")).lower() in tweet.lower():
        kinds.add("mention/handle")
    if a_s.startswith("#") or ("#" + a_s.replace(" ", "")).lower() in tweet.lower():
        kinds.add("hashtag")
    if re.search(r"\d", a_s):
        kinds.add("number")
    if any(re.search(rf"\b{m}\b", a_s.lower()) for m in MONTHS) or re.search(r"\b(19|20)\d{2}\b", a_s):
        kinds.add("date")
    return kinds


def main():
    random.seed(4012)
    train, test = load("train"), load("test")
    L = []
    w = L.append

    w("# TweetQA data report (Stage 0)\n")
    w("Generated by `scripts/data_report.py`. Statistics are computed on **train only**. For test, only size, format and gold-answer presence are checked.\n")

    # ---- splits ----
    w("## Files and splits\n")
    w("| file | rows | unique tweets | unique qids | gold answers present |")
    w("|---|---|---|---|---|")
    for name, rows in [("train.csv", train), ("test.csv", test)]:
        w(f"| {name} | {len(rows)} | {len({r['Tweet'] for r in rows})} | {len({r['qid'] for r in rows})} | "
          f"{sum(1 for r in rows if r['answers'])}/{len(rows)} |")
    w("")
    w("- Columns: `Question, Answer, Tweet, qid`. `Answer` is a numpy-array repr of one or more strings, e.g. `['w nj' 'w nj']`. The items are separated by a space or newline and quoted with `'` or `\"`. Every row parses.")
    w("- **There is no validation split.** The sizes match the original TweetQA train (10,692) and dev (1,086) sets, so `test.csv` is the public dev set. It **has gold answers**.")
    overlap = {r['Tweet'] for r in train} & {r['Tweet'] for r in test}
    w(f"- Tweets shared between train and test: {len(overlap)}.")
    dup_rows = collections.Counter((r['Question'], r['Answer'], r['Tweet']) for r in train)
    w(f"- Train has {sum(c - 1 for c in dup_rows.values())} exact-duplicate rows. 166 rows share a qid, because qid is a hash of the question text and generic questions repeat across tweets.")
    noexist = [r for r in train if r['answers'][0].strip().lower() == 'tweet does not exist']
    w(f"- Train has {len(noexist)} annotation-noise rows with question/answer 'tweet does not exist'.")
    qs_per_tweet = collections.Counter(r['Tweet'] for r in train)
    w(f"- Questions per tweet (train): mean {len(train)/len(qs_per_tweet):.2f}, max {max(qs_per_tweet.values())}. **Any train/validation split must group by tweet** to avoid leakage.\n")

    test_n_ans = collections.Counter(len(r['answers']) for r in test)
    w(f"- Test gold answers per example: {dict(sorted(test_n_ans.items()))}\n")

    # ---- lengths ----
    w("## Lengths in tokens (train; Twitter-aware regex tokeniser)\n")
    tw = [len(tok(r['Tweet'])) for r in {r['Tweet']: r for r in train}.values()]
    qu = [len(tok(r['Question'])) for r in train]
    an = [len(tok(a)) for r in train for a in r['answers']]
    w("| | p50 | p75 | p90 | p95 | p99 | max |")
    w("|---|---|---|---|---|---|---|")
    for name, xs in [("tweet (unique)", tw), ("question", qu), ("answer", an)]:
        p = pct(xs)
        w(f"| {name} | " + " | ".join(str(p[k]) for k in (50, 75, 90, 95, 99, 100)) + " |")
    w(f"\nAnswers ≤ 10 tokens: {100*sum(x <= 10 for x in an)/len(an):.1f}%; ≤ 15: {100*sum(x <= 15 for x in an)/len(an):.1f}%; ≤ 20: {100*sum(x <= 20 for x in an)/len(an):.1f}%.\n")

    n_ans = collections.Counter(len(r['answers']) for r in train)
    w(f"Gold answers per example (train): {dict(sorted(n_ans.items()))}\n")

    # ---- extractiveness ----
    w("## Extractiveness (train)\n")
    def any_sub(r, f):
        t = f(r['Tweet'])
        return any(f(a) and f(a) in t for a in r['answers'])
    def tok_sub(r):
        t = " " + normalise(r['Tweet']) + " "
        return any(normalise(a) and (" " + normalise(a) + " ") in t for a in r['answers'])
    raw = sum(any_sub(r, lambda s: s.lower().strip()) for r in train)
    nrm = sum(tok_sub(r) for r in train)
    all_raw = sum(all(a.lower().strip() in r['Tweet'].lower() for a in r['answers']) for r in train)
    w(f"- At least one gold answer is a case-insensitive substring of the tweet: **{100*raw/len(train):.1f}%**")
    w(f"- After normalisation (lowercase, strip ASCII+Unicode punctuation and articles, collapse whitespace; whole-token match): **{100*nrm/len(train):.1f}%**")
    w(f"- All gold answers are raw substrings: {100*all_raw/len(train):.1f}%")
    tw_tok = lambda r: set(normalise(r['Tweet']).split())
    cover = [max(len(set(normalise(a).split()) & tw_tok(r)) / max(1, len(set(normalise(a).split()))) for a in r['answers']) for r in train]
    w(f"- Every normalised answer token appears somewhere in the tweet (any order): {100*sum(c == 1 for c in cover)/len(cover):.1f}%. At least half the tokens appear: {100*sum(c >= .5 for c in cover)/len(cover):.1f}%. No tokens appear: {100*sum(c == 0 for c in cover)/len(cover):.1f}%")
    w("- The remaining examples are abstractive or paraphrased, so an extractive model's ceiling sits below 100. Stage 1 measures that ceiling (the oracle).\n")

    # byline
    byl = 0; byl_ans = 0
    for r in train:
        m = re.search(r"[—–-]?\s*[^—–(]*\(@\w+\)\s+\w+\s+\d{1,2},\s+\d{4}\s*$", r['Tweet'])
        if m:
            byl += 1
            if any(a.strip() and a.lower().strip() in m.group(0).lower() for a in r['answers']):
                byl_ans += 1
    w(f"- Tweets ending in a `Name (@handle) Month D, YYYY` byline: {100*byl/len(train):.1f}%. An answer lies inside the byline in {100*byl_ans/len(train):.1f}% of all train examples (who/when questions about the poster).\n")

    # ---- question words ----
    w("## Top 15 question first-words (train)\n")
    fw = collections.Counter((tok(r['Question'].lower()) or ['<empty>'])[0] for r in train)
    w("| word | count | % |")
    w("|---|---|---|")
    for word, c in fw.most_common(15):
        w(f"| {word} | {c} | {100*c/len(train):.1f} |")
    w("")

    # ---- answer kinds ----
    w("## Answer types (train, first gold answer)\n")
    kinds = collections.Counter()
    for r in train:
        for k in answer_kind(r['answers'][0], r['Tweet']):
            kinds[k] += 1
    for k in ["mention/handle", "hashtag", "number", "date"]:
        w(f"- {k}: {100*kinds[k]/len(train):.1f}%")
    w("")

    # ---- surface phenomena ----
    w("## Tweet surface phenomena (train, unique tweets)\n")
    ut = list({r['Tweet'] for r in train})
    def share(pat):
        return 100 * sum(1 for t in ut if re.search(pat, t)) / len(ut)
    surface = [("@mention", r"@\w+"), ("#hashtag", r"#\w+"), ("URL", URL.pattern),
               ("elongation (char ×3+)", r"([a-zA-Z])\1\1"), ("HTML entity (`&amp;` etc.)", r"&\w+;")]
    for name, pat in surface:
        w(f"- contains {name}: {share(pat):.1f}%")
    w(f"- contains emoji: {100*sum(1 for t in ut if EMOJI.search(t))/len(ut):.1f}%")
    ans_emoji = sum(1 for r in train if any(EMOJI.search(a) for a in r['answers']))
    ans_hash = sum(1 for r in train if any('#' in a for a in r['answers']))
    ans_at = sum(1 for r in train if any('@' in a for a in r['answers']))
    w(f"- gold answers containing an emoji: {ans_emoji}; containing `#`: {ans_hash}; containing `@`: {ans_at}")
    w("")

    # ---- examples ----
    w("## 10 random train examples (raw)\n")
    for r in random.sample(train, 10):
        w(f"- **Q:** {r['Question']}  \n  **A:** {r['answers']}  \n  **Tweet:** {r['Tweet']}")
    w("")

    # ---- template ----
    w("## Template notebook (`template.ipynb`)\n")
    w("Required section headings, which must not be modified:")
    w("1. `# 2026 CITS4012 Project` (title cell; rename the file with the group id)")
    w("2. `# Readme` (notes to the marker; OOP code goes at the bottom of the notebook)")
    w("3. `# 1.Dataset Processing`")
    w("4. `# 2. Model Implementation`")
    w("5. `# 3.Testing and Evaluation`")
    w("\nAny number of code and markdown cells may be added under each heading.")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    sys.exit(main())
